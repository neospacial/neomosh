// Compile the codec kernels (src/codec/wasm/kernels.c) to WebAssembly with clang, and write
// src/codec/wasm/kernels.wasm and src/codec/wasm-bytes.js (the module as base64, for the build).
// Both outputs are in the repository, so that tools/build.mjs needs only Node.
// Usage: node tools/build-wasm.mjs   (needs clang with the wasm32 target and wasm-ld)
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'src/codec/wasm');
const out = path.join(dir, 'kernels.wasm');

// The CAVLC tables for the C code come from src/codec/tables.js (one source).
const T = await import(path.join(root, 'src/codec/tables.js'));
const arr = (name, a, w) => {
  const rows = Array.isArray(a[0]) || ArrayBuffer.isView(a[0]) ? a : [a];
  const width = w || Math.max(...rows.map((r) => r.length));
  const body = rows.map((r) => '{' + Array.from({ length: width }, (_, i) => r[i] ?? 0).join(', ') + '}').join(',\n  ');
  return rows === a ? `static const uint16_t ${name}[${rows.length}][${width}] = {\n  ${body}\n};\n` :
    `static const uint16_t ${name}[${width}] = ${body};\n`;
};
fs.writeFileSync(path.join(dir, 'tables.h'), '// Generated by tools/build-wasm.mjs from src/codec/tables.js. Do not edit.\n' + [
  arr('COEFF_TOKEN_LEN', T.COEFF_TOKEN_LEN), arr('COEFF_TOKEN_BITS', T.COEFF_TOKEN_BITS),
  arr('CHROMA_DC_COEFF_TOKEN_LEN', Array.from(T.CHROMA_DC_COEFF_TOKEN_LEN)), arr('CHROMA_DC_COEFF_TOKEN_BITS', Array.from(T.CHROMA_DC_COEFF_TOKEN_BITS)),
  arr('TOTAL_ZEROS_LEN', T.TOTAL_ZEROS_LEN, 16), arr('TOTAL_ZEROS_BITS', T.TOTAL_ZEROS_BITS, 16),
  arr('CHROMA_DC_TOTAL_ZEROS_LEN', T.CHROMA_DC_TOTAL_ZEROS_LEN, 4), arr('CHROMA_DC_TOTAL_ZEROS_BITS', T.CHROMA_DC_TOTAL_ZEROS_BITS, 4),
  arr('RUN_BEFORE_LEN', T.RUN_BEFORE_LEN, 16), arr('RUN_BEFORE_BITS', T.RUN_BEFORE_BITS, 16),
  arr('ZIGZAG4x4', Array.from(T.ZIGZAG4x4)), arr('CBP_INTER_TO_CODE', Array.from(T.CBP_INTER_TO_CODE)),
  arr('CBP_INTER_FROM_CODE', Array.from(T.CBP_INTER_FROM_CODE)),
].join('\n'));
const r = spawnSync('clang', [
  '--target=wasm32', '-O3', '-msimd128', '-mbulk-memory', '-nostdlib', '-std=c11', '-Wall', '-Werror',
  '-Wl,--no-entry', '-Wl,--import-memory', '-Wl,--stack-first', '-Wl,-z,stack-size=65536', '-Wl,--export=__heap_base',
  '-o', out, path.join(dir, 'kernels.c'),
], { stdio: 'inherit' });
if (r.status !== 0) process.exit(r.status || 1);
const bytes = fs.readFileSync(out);
fs.writeFileSync(path.join(root, 'src/codec/wasm-bytes.js'),
  '// Generated by tools/build-wasm.mjs from src/codec/wasm/kernels.c. Do not edit.\n' +
  `export const KERNELS_WASM = '${bytes.toString('base64')}';\n`);
console.log(`src/codec/wasm/kernels.wasm (${bytes.length} bytes)`);
